"""API-key provider (API mode): Claude, or any OpenAI-compatible provider the key belongs to.

The HTTP clients live in llm_anthropic.py and llm_openai.py; this file only labels the answers.
(The file keeps its original name from docs/ANSWER_MODES.md section 5.)
"""

from app.generation.base import AnswerMode
from app.generation.generative import GenerativeProvider
from app.generation.llm_base import LLMClient
from app.generation.providers import PROVIDERS


class ApiProvider(GenerativeProvider):
    """Generative answers from the provider the user's API key belongs to."""

    def __init__(self, llm: LLMClient) -> None:
        super().__init__(llm, AnswerMode.API)
        spec = PROVIDERS.get(llm.provider)
        self.label = f"Generated by {llm.model} ({spec.name})" if spec else f"Generated by {llm.model}"


AnthropicProvider = ApiProvider  # former name, kept for readers of docs/ANSWER_MODES.md
