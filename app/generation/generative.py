"""Shared base for generative providers (Claude API, Ollama): grounded prompt + streamed text."""

from collections.abc import Iterator

from app.generation.base import AnswerEvent, AnswerMode, QuestionType
from app.generation.llm_base import LLMClient, LLMError
from app.generation.prompt import SYSTEM_PROMPT, build_user_prompt
from app.schemas import RetrievedChunk


class GenerativeProvider:
    """Streams an LLM's answer to the numbered-sources prompt (same `NO_ANSWER` rule for all)."""

    def __init__(self, llm: LLMClient, mode: AnswerMode) -> None:
        self.llm = llm
        self.mode = mode
        self.name = llm.model
        self.label = f"Generated by {llm.model}"

    def is_available(self) -> tuple[bool, str]:
        """Ask the backend whether it can answer (key valid / server reachable)."""
        try:
            self.llm.check()
        except LLMError as exc:
            return False, str(exc)
        return True, f"Ready: {self.llm.model}."

    def answer(self, question: str, chunks: list[RetrievedChunk], qtype: QuestionType) -> Iterator[AnswerEvent]:
        """Stream the model's grounded answer as token events."""
        for delta in self.llm.stream(SYSTEM_PROMPT, build_user_prompt(question, chunks)):
            yield AnswerEvent("token", delta)
