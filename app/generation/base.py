"""Answer-provider protocol shared by every answer mode (docs/ANSWER_MODES.md section 5).

Every provider gets the same retrieved chunks (same retrieval and no-answer gate for all modes)
and yields the same event types, so the chat service and the frontend have one code path:

* `AnswerEvent("token", text=...)` — answer text, streamed or in one piece; the exact text
  `NO_ANSWER` means "the sources don't contain the answer".
* `AnswerEvent("meta", data=...)` — optional extras: the extracted `span`, its `span_source` and
  `span_char_range`, a `confidence` in [0, 1] and a `hint` for the user.
"""

from collections.abc import Iterator
from dataclasses import dataclass, field
from enum import StrEnum
from typing import Any, Literal, Protocol

from pydantic import BaseModel

from app.schemas import Citation, RetrievedChunk

QuestionType = Literal["factoid", "summary", "explain"]

EXTRACTIVE_LABEL = "Extractive · quoted from your document"


class AnswerMode(StrEnum):
    """How the final answer is produced."""

    LOCAL = "local"
    OLLAMA = "ollama"
    API = "api"


@dataclass(frozen=True)
class AnswerEvent:
    """One item from a provider's answer stream."""

    kind: Literal["token", "meta"]
    text: str = ""
    data: dict[str, Any] = field(default_factory=dict)


class AnswerProvider(Protocol):
    """Turns retrieved passages into an answer."""

    mode: AnswerMode
    name: str  # model name, for display
    label: str  # "Extractive · quoted from your document" | "Generated by <model>"

    def is_available(self) -> tuple[bool, str]:
        """(ok, human-readable reason)."""
        ...

    def answer(self, question: str, chunks: list[RetrievedChunk], qtype: QuestionType) -> Iterator[AnswerEvent]:
        """Yield token and meta events; token text `NO_ANSWER` means no answer."""
        ...


class AnswerResult(BaseModel):
    """The final, assembled answer (also the shape persisted with each assistant message)."""

    mode: AnswerMode
    answerable: bool
    text: str
    span: str | None = None
    span_char_range: tuple[int, int] | None = None
    citations: list[Citation]
    confidence: float | None = None
    label: str


def confidence_words(confidence: float | None) -> str | None:
    """Show confidence as words, not a raw number (docs/ANSWER_MODES.md section 7)."""
    if confidence is None:
        return None
    if confidence >= 0.85:
        return "High match"
    if confidence >= 0.5:
        return "Medium match"
    return "Low match"
